def svg(name, cls="ico"):
    return (
        f'<svg class="{cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        f'stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
        f'{ICONS[name]}</svg>'
    )


_EMOJI_ALT = "|".join(re.escape(k) for k in sorted(EMOJI_MAP, key=len, reverse=True))
# A standalone large emoji inside its own span/div (used as a card icon) -> icon tile
_TILE_RE = re.compile(
    r'<(span|div) style="font-size:\s*\d+px;[^"]*">\s*(' + _EMOJI_ALT + r')\s*</\1>'
)
_ANY_RE = re.compile(_EMOJI_ALT)


def iconize(html):
    html = html.replace("\ufe0f", "")  # emoji variation selectors

    def tile(m):
        tag, emo = m.group(1), m.group(2)
        return f'<{tag} class="ico-tile">{svg(EMOJI_MAP[emo])}</{tag}>'

    html = _TILE_RE.sub(tile, html)

    # Only touch text outside <script> (JSON-LD) blocks.
    parts = re.split(r'(<script\b.*?</script>)', html, flags=re.S)
    for i in range(0, len(parts), 2):
        def inline(m):
            name = EMOJI_MAP[m.group(0)]
            cls = "ico ico-check" if name == "check" else "ico"
            return svg(name, cls)
        parts[i] = _ANY_RE.sub(inline, parts[i])
    return "".join(parts)

